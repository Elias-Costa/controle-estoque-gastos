test('E-43 atualiza vencido e mês na virada e no retorno à tela', async ({ page, context }) => {
  await page.clock.install({ time: new Date('2026-11-30T23:00:00-03:00') })
  await abrirBuild(page)
  await context.setOffline(true)
  await cadastrar(page, 'Lia', '10000', '2026-11-30')
  await voltar(page)
  await page.clock.setSystemTime('2026-11-30T23:59:55-03:00')
  await abrirResumo(page)
  const saldo = page.getByRole('region', { name: 'A receber', exact: true })
  const mes = page.getByLabel('Mês', { exact: true })
  await conferirValor(saldo, 'A vencer', 'R$ 100,00')
  await expect(mes).toHaveValue('11')
  await page.clock.runFor(5100)
  await conferirValor(saldo, '1–30 dias', 'R$ 100,00')
  await expect(mes).toHaveValue('12')
  await mes.selectOption('11')
  await page.clock.setSystemTime('2026-12-31T12:00:00-03:00')
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')))
  await conferirValor(saldo, '31–60 dias', 'R$ 100,00')
  await expect(mes).toHaveValue('11')
})

test('E-43 conserva o prazo digitado diante de outra edição local', async ({ page, context }) => {
  await abrirBuild(page)
  await context.setOffline(true)
  await abrirResumo(page)
  await prazo(page).fill('45')
  const outra = await context.newPage()
  await outra.goto('/')
  await abrirResumo(outra)
  await prazo(outra).fill('60')
  await salvarPrazo(outra).click()
  await expect(outra.getByText('Prazo salvo neste aparelho.', { exact: true })).toBeVisible()
  await salvarPrazo(page).click()
  await expect(page.getByRole('alert')).toContainText('O prazo mudou para 60 dias.')
  await expect(prazo(page)).toHaveValue('45')
  await expect(page.getByText('Disponíveis para venda, parados há mais de 60 dias.', { exact: true })).toBeVisible()
  await salvarPrazo(page).click()
  await expect(page.getByText('Prazo salvo neste aparelho.', { exact: true })).toBeVisible()
  await expect(prazo(outra)).toHaveValue('45')
})

async function abrirBuild(page: Page) {
  await page.goto('/')
  await page.evaluate(() => navigator.serviceWorker.ready.then(() => undefined))
  await page.reload()
  await page.waitForFunction(() => !!navigator.serviceWorker.controller)
}

async function cadastrar(page: Page, nome: string, saldo?: string, vence?: string) {
  await page.getByRole('button', { name: '+ Nova fichinha', exact: true }).click()
  await page.getByLabel('Nome', { exact: true }).fill(nome)
  if (saldo && vence) {
    await page.getByLabel('Já me deve', { exact: true }).fill(saldo)
    await page.getByLabel('Desde', { exact: true }).fill('2026-09-01')
    await page.getByLabel('Vence em', { exact: true }).fill(vence)
  }
  await page.getByRole('button', { name: 'Pronto', exact: true }).click()
  await expect(page.getByRole('heading', { name: nome, exact: true })).toBeVisible()
}

async function confirmarVenda(page: Page) {
  await page.getByRole('button', { name: 'Pronto', exact: true }).click()
  await page.getByRole('button', { name: 'Ver a fichinha', exact: true }).click()
}

async function conferirValor(bloco: Locator, rotulo: string, valor: string) {
  await expect(bloco.getByText(rotulo, { exact: true }).locator('xpath=following-sibling::dd')).toHaveText(valor)
}

async function ampliarTexto(page: Page) {
  await page.addStyleTag({ content: 'html { font-size: 200%; } body { font-size: 36px; }' })
}
