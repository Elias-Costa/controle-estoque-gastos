import { expect, test } from '@playwright/test'
import { fileURLToPath } from 'node:url'
import { abrirApp, entrar, pularSemUsuario } from './apoio.ts'

test('D-076 nome/logo salvos offline, reabertura, restauração em outro aparelho e remoção explícita', async ({ page, context, browser }, info) => {
  pularSemUsuario()
  await abrirApp(page); await context.setOffline(true)
  await page.getByRole('button', { name: /^Produtos/ }).click()
  await page.getByRole('button', { name: 'Divulgar produtos', exact: true }).click()
  await page.getByRole('button', { name: 'Identificar loja', exact: true }).click()
  await expect(page.getByLabel('Nome da loja ou marca', { exact: true })).toHaveValue('')
  await expect(page.getByRole('button', { name: 'Salvar identificação', exact: true })).toBeDisabled()
  await page.getByLabel('Nome da loja ou marca', { exact: true }).fill('Cícera Mult')
  await page.getByLabel('Descrição da loja (opcional)', { exact: true }).fill('Perfumaria, moda íntima, beleza e acessórios para celular')
  await page.getByLabel('Escolher logo', { exact: true }).setInputFiles(fileURLToPath(new URL('../../public/icones/icone-192.png', import.meta.url)))
  await expect(page.getByRole('img', { name: 'Prévia da logo da loja', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Salvar identificação', exact: true }).click()
  await expect(page.getByRole('img', { name: 'Logo da loja', exact: true })).toBeVisible()
  const original = await page.evaluate(async () => window.laboratorio?.repositorioIdentidadeLoja.ler())
  expect(original?.identidade.logo).toMatch(/^data:image\/png;base64,/)
  await page.screenshot({ path: info.outputPath('identidade-salva.png'), fullPage: true })
  await page.reload(); await page.waitForFunction(() => !!window.laboratorio)
  expect(await page.evaluate(async () => window.laboratorio?.repositorioIdentidadeLoja.ler())).toEqual(original)
  await context.setOffline(false); await entrar(page)
  await page.evaluate(async () => window.laboratorio?.sincronizacao.sincronizar())
  await expect.poll(async () => page.evaluate(async () => window.laboratorio?.banco.fila.count())).toBe(0)
  const segundo = await browser.newContext()
  try {
    const outra = await segundo.newPage(); await abrirApp(outra); await entrar(outra)
    await outra.evaluate(async () => window.laboratorio?.sincronizacao.sincronizar())
    expect(await outra.evaluate(async () => window.laboratorio?.repositorioIdentidadeLoja.ler())).toEqual(original)
    await segundo.setOffline(true); await outra.reload(); await outra.waitForFunction(() => !!window.laboratorio)
    expect(await outra.evaluate(async () => window.laboratorio?.repositorioIdentidadeLoja.ler())).toEqual(original)
    await page.getByRole('button', { name: /^Produtos/ }).click()
    await page.getByRole('button', { name: 'Divulgar produtos', exact: true }).click()
    await page.getByRole('button', { name: 'Editar identificação', exact: true }).click()
    await page.getByRole('button', { name: 'Remover logo', exact: true }).click()
    await page.getByLabel('Nome da loja ou marca', { exact: true }).fill('Outra marca de teste')
    await page.getByRole('button', { name: 'Salvar identificação', exact: true }).click()
    await expect(page.getByRole('img', { name: 'Logo da loja', exact: true })).toHaveCount(0)
    await page.evaluate(async () => window.laboratorio?.sincronizacao.sincronizar())
    await segundo.setOffline(false)
    await outra.evaluate(async () => window.laboratorio?.sincronizacao.sincronizar())
    const atualizada = await outra.evaluate(async () => window.laboratorio?.repositorioIdentidadeLoja.ler())
    expect(atualizada?.identidade.nome).toBe('Outra marca de teste')
    expect(atualizada?.identidade.logo).toBeUndefined()
  } finally { await segundo.close() }
})
